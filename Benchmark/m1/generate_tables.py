#!/usr/bin/env python3
"""보존한 280개 원시 결과로 논문 비교 표를 생성한다. 실험은 실행하지 않는다."""

import json
import math
import statistics
from collections import defaultdict
from pathlib import Path

BASE = Path(__file__).resolve().parent
TABLES = BASE.parents[1] / "Paper_m1" / "Tables"
SOURCE_HASH = "c34bd62bee6f07a879d7e4b48d8b9c17e0ca48c34e796425e2bec93ed74e6f93"
INPUTS = {
    "square": "squares_k7_k10_m1pro_20260929_run1.jsonl",
    "batch": "batch_q1_q10_m1pro_20260929_resume1.jsonl",
}
SCHEMES = ("lamp", "independent_zkmatrix_optimized_bn254")


def collect():
    groups = defaultdict(list)
    for workload, filename in INPUTS.items():
        rows = [json.loads(line) for line in (BASE / filename).read_text().splitlines() if line.strip()]
        if len(rows) != (80 if workload == "square" else 200):
            raise ValueError(f"Unexpected record count: {filename}")
        for row in rows:
            if row.get("verification_succeeded") is not True or row["protocol_path"] != workload:
                raise ValueError("Unverified result or unexpected protocol path")
            if row["source"]["source_tree_sha256"] != SOURCE_HASH:
                raise ValueError("Unexpected source fingerprint")
            host = row["host"]
            if (host["processor"], host["cpu_count"], host["memory_bytes"], host["gomaxprocs"], host["go"]) != (
                "Apple M1 Pro", 10, 32 * (1 << 30), 10, "go version go1.26.2 darwin/arm64"
            ):
                raise ValueError("Unexpected host, thread budget, or toolchain")
            scheme = row["scheme"]
            if scheme not in SCHEMES:
                raise ValueError("Unexpected scheme")
            dimensions = row["dimensions"]
            n = dimensions["K"] if scheme == "lamp" else dimensions["n"]
            if scheme != "lamp" and not dimensions["m"] == dimensions["inner"] == n:
                raise ValueError("Expected square matrices")
            cfg = row["experiment_config"]
            if cfg["repetitions"] != 10 or cfg["threads"] != 10:
                raise ValueError("Unexpected repetition count or thread budget")
            if scheme == "lamp" and (row["query_count"] != 309 or cfg["rho"] != "1/2"):
                raise ValueError("Unexpected LAMP parameters")
            groups[(workload, n, row["batch_q"], scheme)].append(row)
    expected = {(w, n, q, s) for w, sizes, batches in (
        ("square", [128, 256, 512, 1024], [1]), ("batch", [128], range(1, 11))
    ) for n in sizes for q in batches for s in SCHEMES}
    if set(groups) != expected:
        raise ValueError("Incomplete or unexpected comparison grid")
    summaries = {}
    for key, rows in groups.items():
        if len(rows) != 10:
            raise ValueError(f"Expected ten verified repetitions: {key}")
        metrics = {}
        for name, values in {
            "prove_seconds": [r["timings_seconds"]["prove"] for r in rows],
            "verify_ms": [1000 * r["timings_seconds"]["verify"] for r in rows],
            "proof_bytes": [r["compressed_payload_bytes"] for r in rows],
            "statement_bytes": [r["statement_bytes"] for r in rows],
        }.items():
            if any(type(v) not in (int, float) or not math.isfinite(v) or v <= 0 for v in values):
                raise ValueError(f"Invalid metric: {key}, {name}")
            metrics[name] = {"mean": statistics.mean(values), "sample_sd": statistics.stdev(values)}
        summaries[key] = {"repetitions": len(rows), **metrics}
    return summaries


def time_cell(metric, places):
    return f"${metric['mean']:.{places}f} \\pm {metric['sample_sd']:.{places}f}$"


def bytes_cell(metric):
    value = metric["mean"]
    return (f"{value:,.0f}" if value == int(value) else f"{value:,.1f}").replace(",", "{,}")


def main():
    summaries = collect()
    header = "% Generated by Benchmark/m1/generate_tables.py from ten verified repetitions per condition.\n"
    square = []
    for n in (128, 256, 512, 1024):
        for scheme, label in ((SCHEMES[0], r"\(\protocol\)"), (SCHEMES[1], "zkMatrix")):
            m = summaries[("square", n, 1, scheme)]
            cells = [str(n), label, time_cell(m["prove_seconds"], 3), time_cell(m["verify_ms"], 2), bytes_cell(m["proof_bytes"]), bytes_cell(m["statement_bytes"])]
            square.append(" & ".join(cells) + r" \\")
        if n != 1024:
            square.append(r"\midrule")
    batch = []
    for q in range(1, 11):
        pair = [summaries[("batch", 128, q, s)] for s in SCHEMES]
        cells = [str(q)]
        for metric, places in (("prove_seconds", 3), ("verify_ms", 2)):
            cells.extend(time_cell(m[metric], places) for m in pair)
        for metric in ("proof_bytes", "statement_bytes"):
            cells.extend(bytes_cell(m[metric]) for m in pair)
        batch.append(" & ".join(cells) + r" \\")
    (TABLES / "zkMatrix_square_rows.tex").write_text(header + "\n".join(square) + "\n")
    (TABLES / "zkMatrix_batch_rows.tex").write_text(header + "\n".join(batch) + "\n")
    output = [{"workload": k[0], "dimension": k[1], "batch_q": k[2], "scheme": k[3], **v} for k, v in sorted(summaries.items())]
    (BASE / "measurements.json").write_text(json.dumps(output, indent=2) + "\n")
    print(f"Verified 280 records in {len(summaries)} conditions; wrote two tables and measurements.json.")


if __name__ == "__main__":
    main()
